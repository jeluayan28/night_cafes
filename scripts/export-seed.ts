// Generates supabase/seed.sql from the OpenStreetMap snapshot, using the same importer
// the app uses. Re-runnable: rows upsert on (source, source_ref).
//
//   npm run db:seed
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { CafeRecord } from '../src/lib/model/cafe-record';
import { osmToRecord } from '../src/lib/model/osm-import';
import type { Snapshot } from '../src/types';

const root = new URL('../', import.meta.url);
const snapshot = JSON.parse(readFileSync(new URL('src/data/cafes.json', root), 'utf8')) as Snapshot;

const str = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]) => (v.length ? `array[${v.map(str).join(', ')}]::text[]` : `'{}'::text[]`);
const num = (v: number) => String(v);

function row(r: CafeRecord): string {
  return `  (${[
    str(r.name),
    str(r.slug),
    str(r.description),
    str(r.address),
    str(r.barangay),
    num(r.latitude),
    num(r.longitude),
    `${str(JSON.stringify(r.weekly_hours))}::jsonb`,
    r.price_range ? `${str(r.price_range)}::public.price_range` : 'null',
    arr(r.amenities),
    str(r.image_url),
    arr(r.photo_urls),
    str(r.phone),
    str(r.website_url),
    `${str(r.verification_status)}::public.verification_status`,
    r.last_verified_at ? `${str(r.last_verified_at)}::timestamptz` : 'null',
    r.last_verified_precision ? `${str(r.last_verified_precision)}::public.verification_precision` : 'null',
    arr(r.cuisine),
    str(r.notes),
    str(r.source),
    str(r.source_ref),
    `${str(r.created_at)}::timestamptz`,
    `${str(r.updated_at)}::timestamptz`,
  ].join(', ')})`;
}

const COLUMNS = [
  'name', 'slug', 'description', 'address', 'barangay', 'latitude', 'longitude', 'weekly_hours', 'price_range',
  'amenities', 'image_url', 'photo_urls', 'phone', 'website_url', 'verification_status', 'last_verified_at',
  'last_verified_precision', 'cuisine', 'notes', 'source', 'source_ref', 'created_at', 'updated_at',
];
// On re-import keep created_at, refresh everything else. (id, directions_url, geog, search_text are generated.)
const UPDATE = COLUMNS.filter((c) => c !== 'created_at' && c !== 'updated_at').map((c) => `${c} = excluded.${c}`);

const records = snapshot.cafes.map((c) => osmToRecord(c, snapshot.generatedAt));
const sql = `-- Generated by scripts/export-seed.ts from the OpenStreetMap snapshot (${snapshot.osmTimestamp ?? snapshot.generatedAt}).
-- ${records.length} cafés. Safe to re-run: upserts on (source, source_ref).
insert into public.cafes (${COLUMNS.join(', ')})
values
${records.map(row).join(',\n')}
on conflict (source, source_ref) do update set
  ${UPDATE.join(',\n  ')},
  updated_at = now();
`;

const out = fileURLToPath(new URL('supabase/seed.sql', root));
writeFileSync(out, sql);
console.log(`Wrote ${records.length} cafés to ${out}`);
